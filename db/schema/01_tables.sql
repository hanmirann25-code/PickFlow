-- PickFlow 스키마 — 테이블
--
-- 실행 순서: 01_tables → 02_indexes → 03_sequences
-- 두 번 실행해도 깨지지 않는다 (Oracle 23ai의 IF NOT EXISTS 사용).
--
-- 네이밍·타입은 .cursor/rules/oracle.mdc를 따른다.
-- 문자열은 VARCHAR2(n CHAR), 일시는 TIMESTAMP WITH TIME ZONE, PK는 IDENTITY.

-- 사용자. 역할에 따라 볼 수 있는 화면과 실행할 수 있는 상태 전이가 달라진다.
CREATE TABLE IF NOT EXISTS USERS (
  ID             NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  EMAIL          VARCHAR2(255 CHAR)       NOT NULL,
  NAME           VARCHAR2(100 CHAR)       NOT NULL,
  PASSWORD_HASH  VARCHAR2(255 CHAR)       NOT NULL,
  ROLE           VARCHAR2(20 CHAR)        NOT NULL,
  CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USERS       PRIMARY KEY (ID),
  CONSTRAINT UX_USERS_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_USERS_ROLE  CHECK (ROLE IN ('ADMIN', 'OPERATOR', 'PICKER', 'VIEWER'))
);

-- 상품(SKU). 같은 티셔츠라도 색·사이즈가 다르면 다른 행이다.
CREATE TABLE IF NOT EXISTS PRODUCTS (
  ID           NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  SKU          VARCHAR2(50 CHAR)        NOT NULL,
  NAME         VARCHAR2(200 CHAR)       NOT NULL,
  BARCODE      VARCHAR2(50 CHAR),
  OPTION_NAME  VARCHAR2(100 CHAR),
  UNIT_PRICE   NUMBER(15, 2)            DEFAULT 0 NOT NULL,
  CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_PRODUCTS         PRIMARY KEY (ID),
  CONSTRAINT UX_PRODUCTS_SKU     UNIQUE (SKU),
  -- 스캔한 바코드로 상품을 특정해야 하므로 중복을 허용하지 않는다.
  -- 바코드가 없는 상품은 있을 수 있어 NULL은 허용한다.
  CONSTRAINT UX_PRODUCTS_BARCODE UNIQUE (BARCODE),
  CONSTRAINT CK_PRODUCTS_PRICE   CHECK (UNIT_PRICE >= 0)
);

-- 창고 내 위치. CODE는 A-01-03-2 = 구역-통로-선반-단.
-- SORT_ORDER는 피킹 동선의 정렬 기준이다. 웨이브는 이 순서대로 한 방향으로 훑는다.
-- 주의: LEVEL은 오라클 예약어(CONNECT BY LEVEL)라 컬럼명으로 쓸 수 없어 LEVEL_NO로 둔다.
CREATE TABLE IF NOT EXISTS LOCATIONS (
  ID          NUMBER(10)        GENERATED BY DEFAULT AS IDENTITY,
  CODE        VARCHAR2(30 CHAR) NOT NULL,
  ZONE        VARCHAR2(10 CHAR) NOT NULL,
  AISLE       NUMBER(10)        NOT NULL,
  RACK        NUMBER(10)        NOT NULL,
  LEVEL_NO    NUMBER(10)        NOT NULL,
  SORT_ORDER  NUMBER(10)        NOT NULL,
  CONSTRAINT PK_LOCATIONS      PRIMARY KEY (ID),
  CONSTRAINT UX_LOCATIONS_CODE UNIQUE (CODE)
);

-- 로케이션별 재고.
-- 가용 재고는 저장하지 않는다. 항상 QTY_ON_HAND - QTY_ALLOCATED로 계산한다.
CREATE TABLE IF NOT EXISTS INVENTORY (
  ID             NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  PRODUCT_ID     NUMBER(10)               NOT NULL,
  LOCATION_ID    NUMBER(10)               NOT NULL,
  QTY_ON_HAND    NUMBER(10)               DEFAULT 0 NOT NULL,
  QTY_ALLOCATED  NUMBER(10)               DEFAULT 0 NOT NULL,
  UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_INVENTORY           PRIMARY KEY (ID),
  CONSTRAINT FK_INVENTORY_PRODUCT   FOREIGN KEY (PRODUCT_ID)  REFERENCES PRODUCTS (ID),
  CONSTRAINT FK_INVENTORY_LOCATION  FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS (ID),
  -- 정합성 조건 1·2(기획서 8-5)를 DB에서 직접 막는다.
  -- 앱 로직이나 프로시저가 틀려도 음수 가용재고는 애초에 저장되지 않는다.
  CONSTRAINT CK_INVENTORY_QTY CHECK (
    QTY_ON_HAND >= 0
    AND QTY_ALLOCATED >= 0
    AND QTY_ALLOCATED <= QTY_ON_HAND
  )
);

-- 주문. 상태 전이는 lib/order-graph.ts의 정의만 따른다.
-- 여기 CHECK는 그 정의를 벗어난 값이 저장되는 것을 막는 마지막 방어선이다.
CREATE TABLE IF NOT EXISTS ORDERS (
  ID               NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  ORDER_NO         VARCHAR2(30 CHAR)        NOT NULL,
  CHANNEL          VARCHAR2(30 CHAR)        NOT NULL,
  RECIPIENT_NAME   VARCHAR2(100 CHAR)       NOT NULL,
  RECIPIENT_PHONE  VARCHAR2(30 CHAR),
  ADDRESS          VARCHAR2(500 CHAR),
  STATUS           VARCHAR2(20 CHAR)        DEFAULT 'RECEIVED' NOT NULL,
  ORDERED_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
  DUE_AT           TIMESTAMP WITH TIME ZONE,
  CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_ORDERS          PRIMARY KEY (ID),
  CONSTRAINT UX_ORDERS_ORDER_NO UNIQUE (ORDER_NO),
  CONSTRAINT CK_ORDERS_STATUS   CHECK (STATUS IN (
    'RECEIVED', 'ALLOCATED', 'PICKING', 'PACKED', 'SHIPPED',
    'BACKORDER', 'HOLD', 'CANCELLED'
  ))
);

-- 주문의 상품별 줄. 부분 할당·부분 피킹 상태를 여기서 추적한다.
CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
  ID             NUMBER(10)        GENERATED BY DEFAULT AS IDENTITY,
  ORDER_ID       NUMBER(10)        NOT NULL,
  PRODUCT_ID     NUMBER(10)        NOT NULL,
  QTY            NUMBER(10)        NOT NULL,
  ALLOCATED_QTY  NUMBER(10)        DEFAULT 0 NOT NULL,
  PICKED_QTY     NUMBER(10)        DEFAULT 0 NOT NULL,
  STATUS         VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
  CONSTRAINT PK_ORDER_ITEMS         PRIMARY KEY (ID),
  CONSTRAINT FK_ORDER_ITEMS_ORDER   FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS (ID),
  CONSTRAINT FK_ORDER_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID),
  CONSTRAINT CK_ORDER_ITEMS_STATUS  CHECK (STATUS IN (
    'PENDING', 'ALLOCATED', 'PICKED', 'PACKED', 'SHIPPED', 'CANCELLED'
  )),
  -- 정합성 조건 4(SHIPPED 주문은 PICKED_QTY = QTY)의 전제.
  -- 요청 수량보다 많이 할당하거나 많이 피킹할 수는 없다.
  CONSTRAINT CK_ORDER_ITEMS_QTY CHECK (
    QTY > 0
    AND ALLOCATED_QTY >= 0 AND ALLOCATED_QTY <= QTY
    AND PICKED_QTY >= 0 AND PICKED_QTY <= QTY
  )
);

-- 피킹 웨이브. 여러 주문의 피킹을 한 묶음으로 만든 것.
CREATE TABLE IF NOT EXISTS PICKING_WAVES (
  ID                NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  WAVE_NO           VARCHAR2(30 CHAR)        NOT NULL,
  STATUS            VARCHAR2(20 CHAR)        DEFAULT 'READY' NOT NULL,
  ASSIGNED_USER_ID  NUMBER(10),
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_PICKING_WAVES         PRIMARY KEY (ID),
  CONSTRAINT UX_PICKING_WAVES_NO      UNIQUE (WAVE_NO),
  CONSTRAINT FK_PICKING_WAVES_USER    FOREIGN KEY (ASSIGNED_USER_ID) REFERENCES USERS (ID),
  CONSTRAINT CK_PICKING_WAVES_STATUS  CHECK (STATUS IN ('READY', 'IN_PROGRESS', 'DONE'))
);

-- 웨이브 안의 개별 피킹 작업. SORT_ORDER가 작업자가 도는 순서다.
CREATE TABLE IF NOT EXISTS PICKING_TASKS (
  ID             NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  WAVE_ID        NUMBER(10)               NOT NULL,
  ORDER_ITEM_ID  NUMBER(10)               NOT NULL,
  LOCATION_ID    NUMBER(10)               NOT NULL,
  QTY            NUMBER(10)               NOT NULL,
  PICKED_QTY     NUMBER(10)               DEFAULT 0 NOT NULL,
  STATUS         VARCHAR2(20 CHAR)        DEFAULT 'PENDING' NOT NULL,
  SORT_ORDER     NUMBER(10)               NOT NULL,
  UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_PICKING_TASKS            PRIMARY KEY (ID),
  CONSTRAINT FK_PICKING_TASKS_WAVE       FOREIGN KEY (WAVE_ID)       REFERENCES PICKING_WAVES (ID),
  CONSTRAINT FK_PICKING_TASKS_ITEM       FOREIGN KEY (ORDER_ITEM_ID) REFERENCES ORDER_ITEMS (ID),
  CONSTRAINT FK_PICKING_TASKS_LOCATION   FOREIGN KEY (LOCATION_ID)   REFERENCES LOCATIONS (ID),
  CONSTRAINT CK_PICKING_TASKS_STATUS     CHECK (STATUS IN ('PENDING', 'DONE', 'SKIPPED')),
  CONSTRAINT CK_PICKING_TASKS_QTY        CHECK (QTY > 0 AND PICKED_QTY >= 0 AND PICKED_QTY <= QTY)
);

-- 출고. 택배사에 넘긴 시점의 기록. 이때 재고가 실제로 차감된다.
CREATE TABLE IF NOT EXISTS SHIPMENTS (
  ID           NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  ORDER_ID     NUMBER(10)               NOT NULL,
  COURIER      VARCHAR2(50 CHAR)        NOT NULL,
  TRACKING_NO  VARCHAR2(50 CHAR)        NOT NULL,
  SHIPPED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY   NUMBER(10),
  CONSTRAINT PK_SHIPMENTS          PRIMARY KEY (ID),
  CONSTRAINT FK_SHIPMENTS_ORDER    FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS (ID),
  CONSTRAINT FK_SHIPMENTS_USER     FOREIGN KEY (CREATED_BY) REFERENCES USERS (ID),
  -- 같은 송장번호가 두 주문에 붙는 일은 없어야 한다. 엑셀 일괄 업로드(S-08)의 방어선.
  CONSTRAINT UX_SHIPMENTS_TRACKING UNIQUE (TRACKING_NO)
);

-- 재고 변동 이력. 델타만 쌓는다. 정합성 조건 6의 검사 대상.
CREATE TABLE IF NOT EXISTS INVENTORY_TRANSACTIONS (
  ID           NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  PRODUCT_ID   NUMBER(10)               NOT NULL,
  LOCATION_ID  NUMBER(10)               NOT NULL,
  DELTA        NUMBER(10)               NOT NULL,
  TX_TYPE      VARCHAR2(20 CHAR)        NOT NULL,
  REF_TYPE     VARCHAR2(30 CHAR),
  REF_ID       NUMBER(10),
  CREATED_BY   NUMBER(10),
  CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_INVENTORY_TX          PRIMARY KEY (ID),
  CONSTRAINT FK_INVENTORY_TX_PRODUCT  FOREIGN KEY (PRODUCT_ID)  REFERENCES PRODUCTS (ID),
  CONSTRAINT FK_INVENTORY_TX_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS (ID),
  CONSTRAINT FK_INVENTORY_TX_USER     FOREIGN KEY (CREATED_BY)  REFERENCES USERS (ID),
  CONSTRAINT CK_INVENTORY_TX_TYPE     CHECK (TX_TYPE IN ('ALLOCATE', 'PICK', 'SHIP', 'ADJUST')),
  -- 0짜리 이력은 남길 이유가 없다. 남으면 조건 6의 합계 검증만 흐려진다.
  CONSTRAINT CK_INVENTORY_TX_DELTA    CHECK (DELTA <> 0)
);

-- 감사 로그. 기록 없는 상태 변경은 허용하지 않는다 (정합성 조건 5).
-- BEFORE/AFTER는 오라클에 jsonb가 없으므로 CLOB + IS JSON으로 둔다.
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
  ID           NUMBER(10)               GENERATED BY DEFAULT AS IDENTITY,
  USER_ID      NUMBER(10),
  ACTION       VARCHAR2(50 CHAR)        NOT NULL,
  TARGET_TYPE  VARCHAR2(30 CHAR)        NOT NULL,
  TARGET_ID    NUMBER(10)               NOT NULL,
  BEFORE_JSON  CLOB,
  AFTER_JSON   CLOB,
  CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_AUDIT_LOGS      PRIMARY KEY (ID),
  CONSTRAINT FK_AUDIT_LOGS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
  CONSTRAINT CK_AUDIT_LOGS_BEFORE CHECK (BEFORE_JSON IS JSON),
  CONSTRAINT CK_AUDIT_LOGS_AFTER  CHECK (AFTER_JSON IS JSON)
);

-- 멱등키. 오프라인 큐가 같은 요청을 두 번 보내도 한 번만 처리되게 하는 근거 (정합성 조건 8).
-- 같은 키가 다시 오면 저장해둔 RESPONSE_JSON을 그대로 돌려준다.
CREATE TABLE IF NOT EXISTS IDEMPOTENCY_KEYS (
  IDEMPOTENCY_KEY  VARCHAR2(100 CHAR)       NOT NULL,
  USER_ID          NUMBER(10),
  RESPONSE_JSON    CLOB,
  CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_IDEMPOTENCY_KEYS      PRIMARY KEY (IDEMPOTENCY_KEY),
  CONSTRAINT FK_IDEMPOTENCY_KEYS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
  CONSTRAINT CK_IDEMPOTENCY_RESPONSE  CHECK (RESPONSE_JSON IS JSON)
);
